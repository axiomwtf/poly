//! crates.io publishing for Poly projects.
//!
//! Poly packages are `.vfsx.tar.zst` archives built from `poly.ini`. For
//! crates.io compatibility we additionally emit a `.crate` file: a gzipped
//! tarball of the project sources plus `poly.ini`/`poly.lock` and a stub
//! `Cargo.toml`. The stub exists only so the registry accepts the upload —
//! `poly.ini` is the source of truth and `cargo` cannot meaningfully build
//! the crate (its dependency list is intentionally empty).

use anyhow::{Context, Result};
use poly_config::Config;
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

const CRATES_IO_PUBLISH_URL: &str = "https://crates.io/api/v1/crates/new";
const SKIP_DIRS: &[&str] = &["target", "dist", "node_modules", ".git"];

pub struct CrateArchive {
    pub bytes: Vec<u8>,
    pub sha256: String,
}

fn should_skip(rel: &Path) -> bool {
    rel.components().any(|c| {
        SKIP_DIRS.contains(&c.as_os_str().to_string_lossy().as_ref())
    })
}

/// Generate the stub Cargo.toml content for registry compatibility.
/// Includes a single autodiscovered-style target pointing at the publish
/// target's first source so cargo doesn't reject the manifest for having
/// no targets.
fn stub_cargo_toml(config: &Config, crate_name: &str, target_id: &str) -> String {
    let p = &config.project;
    let edition = p.edition.as_deref().unwrap_or("2021");
    let mut out = String::new();
    out.push_str("# THIS FILE IS A STUB GENERATED BY POLY.\n");
    out.push_str("# This package is built with Poly (poly.ini / poly.lock).\n");
    out.push_str("# Install Poly to use this package; cargo cannot resolve its\n");
    out.push_str("# dependencies because they are declared in poly.ini instead.\n\n");
    out.push_str("[package]\n");
    out.push_str(&format!("name = {:?}\n", crate_name));
    out.push_str(&format!("version = {:?}\n", p.version));
    out.push_str(&format!("edition = {:?}\n", edition));
    let description = p
        .description
        .clone()
        .unwrap_or_else(|| "A stub Cargo.toml generated by Poly; see poly.ini for the real manifest.".to_string());
    out.push_str(&format!("description = {:?}\n", description));
    if let Some(l) = &p.license {
        out.push_str(&format!("license = {:?}\n", l));
    }
    if let Some(lf) = &p.license_file {
        out.push_str(&format!("license-file = {:?}\n", lf));
    }
    if let Some(h) = &p.homepage {
        out.push_str(&format!("homepage = {:?}\n", h));
    }
    if let Some(d) = &p.documentation {
        out.push_str(&format!("documentation = {:?}\n", d));
    }
    if let Some(r) = &p.repository {
        out.push_str(&format!("repository = {:?}\n", r));
    }
    if let Some(r) = &p.readme {
        out.push_str(&format!("readme = {:?}\n", r));
    }
    if !p.keywords.is_empty() {
        out.push_str(&format!("keywords = {:?}\n", p.keywords));
    }
    if !p.categories.is_empty() {
        out.push_str(&format!("categories = {:?}\n", p.categories));
    }
    if !p.authors.is_empty() {
        out.push_str(&format!("authors = {:?}\n", p.authors));
    }

    // Declare one target so the manifest is valid for cargo/crates.io.
    // The path is relative to the .crate root (= project root).
    if let Some(target) = config.targets.get(target_id) {
        if let Some(src) = target.sources.first() {
            if target.type_ == "lib" {
                out.push_str(&format!("\n[lib]\npath = {:?}\n", src));
            } else {
                out.push_str(&format!(
                    "\n[[bin]]\nname = {:?}\npath = {:?}\n",
                    crate_name, src
                ));
            }
        }
    }
    out
}

/// Collect files under `root` (relative paths), skipping build dirs.
fn collect_files(root: &Path) -> Result<Vec<(PathBuf, PathBuf)>> {
    let mut files = Vec::new();
    if !root.is_dir() {
        return Ok(files);
    }
    for entry in walkdir::WalkDir::new(root)
        .into_iter()
        .filter_entry(|e| {
            !SKIP_DIRS.contains(&e.file_name().to_string_lossy().as_ref())
        })
    {
        let entry = entry?;
        if entry.file_type().is_file() {
            let abs = entry.path();
            let rel = abs
                .strip_prefix(root)
                .with_context(|| format!("strip_prefix failed for {}", abs.display()))?;
            if should_skip(rel) {
                continue;
            }
            files.push((abs.to_path_buf(), rel.to_path_buf()));
        }
    }
    Ok(files)
}

/// crates.io requires `[package] name` in Cargo.toml to match the publish
/// metadata name.
///
/// Naming rules:
/// - `[publish] crateName` set + multiple Rust targets →
///   `{crateName}-{suffix}` where suffix is the target id with the
///   `{project}-` prefix stripped (poly-tools → axiom-poly-tools).
/// - `[publish] crateName` set + single target → `crateName`.
/// - No override → the target id itself (poly-config, my-app, ...).
pub fn crate_name_for(config: &Config, target_id: &str) -> String {
    let rust_targets: Vec<String> = publish_target_specs(config)
        .into_iter()
        .filter(|t| t.starts_with("rust:"))
        .collect();
    let multi = rust_targets.len() > 1;

    if let Some(base) = config
        .publish
        .as_ref()
        .and_then(|p| p.crate_name.as_ref())
    {
        let base = base.replace('_', "-");
        if !multi {
            return base;
        }
        let prefix = format!("{}-", config.project.name.replace('_', "-"));
        let suffix = target_id
            .strip_prefix(&prefix)
            .unwrap_or(target_id)
            .replace('_', "-");
        return format!("{}-{}", base, suffix);
    }
    target_id.replace('_', "-")
}

/// The `lang:target` specs publish will act on: [publish] targets, falling
/// back to [build.default] targets.
fn publish_target_specs(config: &Config) -> Vec<String> {
    if let Some(p) = &config.publish {
        if !p.targets.is_empty() {
            return p.targets.clone();
        }
    }
    config.build.default.targets.clone()
}

/// Build the `.crate` archive for one publish target.
/// The archive contains the ENTIRE project source tree (so `poly install`
/// can compile it), `poly.ini`, `poly.lock`, and a stub
/// `Cargo.toml`/`Cargo.toml.orig`.
pub fn build_crate_archive(
    config: &Config,
    target_id: &str,
    project_root: &Path,
) -> Result<CrateArchive> {
    let crate_name = crate_name_for(config, target_id);
    let root = project_root.canonicalize().unwrap_or_else(|_| project_root.to_path_buf());

    // name-version prefix for tar entries
    let prefix = format!("{}-{}", crate_name, config.project.version);

    let mut files: BTreeMap<PathBuf, Vec<u8>> = BTreeMap::new();

    for (abs, rel) in collect_files(&root)? {
        // Skip any pre-existing Cargo.toml — we generate the stub.
        if rel == Path::new("Cargo.toml") || rel == Path::new("Cargo.toml.orig") {
            continue;
        }
        let data = std::fs::read(&abs)
            .with_context(|| format!("Failed to read {}", abs.display()))?;
        files.insert(rel, data);
    }

    let toml = stub_cargo_toml(config, &crate_name, target_id);
    files.insert(PathBuf::from("Cargo.toml"), toml.clone().into_bytes());
    files.insert(PathBuf::from("Cargo.toml.orig"), toml.into_bytes());

    // tar.gz
    let encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());
    let mut tar = tar::Builder::new(encoder);
    for (rel, data) in &files {
        let arcname = format!("{}/{}", prefix, rel.to_string_lossy().replace('\\', "/"));
        let mut header = tar::Header::new_gnu();
        header.set_size(data.len() as u64);
        header.set_mode(0o644);
        header.set_cksum();
        tar.append_data(&mut header, &arcname, data.as_slice())?;
    }
    let encoder = tar.into_inner()?;
    let bytes = encoder.finish()?;
    let sha256 = hex::encode(Sha256::digest(&bytes));

    Ok(CrateArchive { bytes, sha256 })
}

/// Path to Poly's own credentials store: ~/.config/poly/credentials.toml
pub fn credentials_path() -> Option<PathBuf> {
    Some(dirs::config_dir()?.join("poly").join("credentials.toml"))
}

/// Save a crates.io API token to Poly's credentials file.
pub fn save_token(token: &str, registry: &str) -> Result<PathBuf> {
    let path = credentials_path().context("Cannot determine config directory")?;
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    // Preserve other sections if the file exists.
    let mut text = std::fs::read_to_string(&path).unwrap_or_default();
    let section = format!("[registries.{}]", registry);
    let entry = format!("token = {:?}\n", token);
    if let Some(start) = text.find(&section) {
        let rest = &text[start..];
        let end = rest[1..]
            .find("\n[")
            .map(|i| start + 1 + i)
            .unwrap_or(text.len());
        text.replace_range(start..end, &format!("{}{}", section, entry));
    } else {
        if !text.is_empty() && !text.ends_with('\n') {
            text.push('\n');
        }
        text.push_str(&format!("\n{}{}", section, entry));
    }
    std::fs::write(&path, text)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o600));
    }
    Ok(path)
}

/// Remove a registry's token from Poly's credentials file.
pub fn clear_token(registry: &str) -> Result<bool> {
    let Some(path) = credentials_path() else {
        return Ok(false);
    };
    if !path.is_file() {
        return Ok(false);
    }
    let text = std::fs::read_to_string(&path)?;
    let section = format!("[registries.{}]", registry);
    if !text.contains(&section) {
        return Ok(false);
    }
    // Remove the whole [registries.X] section (up to next '[' header or EOF).
    let start = text.find(&section).unwrap();
    let rest = &text[start + section.len()..];
    let end = rest
        .find("\n[")
        .map(|i| start + section.len() + i + 1)
        .unwrap_or(text.len());
    let mut new_text = String::with_capacity(text.len());
    new_text.push_str(&text[..start]);
    new_text.push_str(&text[end..]);
    std::fs::write(&path, new_text)?;
    Ok(true)
}

/// Read a token for `registry` from Poly's credentials file.
fn load_poly_token(registry: &str) -> Option<String> {
    let path = credentials_path()?;
    let text = std::fs::read_to_string(path).ok()?;
    let section = format!("[registries.{}]", registry);
    let start = text.find(&section)?;
    let rest = &text[start + section.len()..];
    let end = rest.find("\n[").unwrap_or(rest.len());
    let body = &rest[..end];
    for line in body.lines() {
        if let Some((k, v)) = line.split_once('=') {
            if k.trim() == "token" {
                let v = v.trim().trim_matches('"');
                if !v.is_empty() {
                    return Some(v.to_string());
                }
            }
        }
    }
    None
}

/// Resolve a crates.io API token: CARGO_REGISTRY_TOKEN env var,
/// then Poly's credentials file, then ~/.cargo/credentials.toml.
pub fn resolve_crates_io_token() -> Option<String> {
    if let Ok(t) = std::env::var("CARGO_REGISTRY_TOKEN") {
        if !t.is_empty() {
            return Some(t);
        }
    }
    if let Some(t) = load_poly_token("crates-io") {
        return Some(t);
    }
    let creds = dirs::home_dir()?.join(".cargo/credentials.toml");
    let text = std::fs::read_to_string(creds).ok()?;
    let mut in_registry = false;
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_registry = line == "[registry]";
            continue;
        }
        if let Some((key, val)) = line.split_once('=') {
            let key = key.trim();
            let val = val.trim().trim_matches('"');
            if key == "registry-token" || (in_registry && key == "token") {
                if !val.is_empty() {
                    return Some(val.to_string());
                }
            }
        }
    }
    None
}

/// Download a `.crate` file from crates.io.
/// `package` may be `name` or `name@version`. Returns (crate_bytes, version).
pub async fn download_crate(package: &str, token: Option<&str>) -> Result<(Vec<u8>, String)> {
    let (name, version) = match package.split_once('@') {
        Some((n, v)) => (n.to_string(), Some(v.to_string())),
        None => (package.to_string(), None),
    };

    let client = reqwest::Client::builder()
        .user_agent(concat!("poly/", env!("CARGO_PKG_VERSION")))
        .build()?;
    let version = match version {
        Some(v) => v,
        None => {
            let mut req = client.get(format!("https://crates.io/api/v1/crates/{}", name));
            if let Some(t) = token {
                req = req.bearer_auth(t);
            }
            let resp = req.send().await.context("crates.io crate lookup failed")?;
            if !resp.status().is_success() {
                anyhow::bail!("crate not found on crates.io: {}", name);
            }
            let v: serde_json::Value = resp.json().await?;
            v.pointer("/crate/newest_version")
                .and_then(|x| x.as_str())
                .context("crates.io response missing newest_version")?
                .to_string()
        }
    };

    let url = format!(
        "https://crates.io/api/v1/crates/{}/{}/download",
        name, version
    );
    let mut req = client.get(&url);
    if let Some(t) = token {
        req = req.bearer_auth(t);
    }
    let resp = req.send().await.context("crates.io download failed")?;
    if !resp.status().is_success() {
        anyhow::bail!("failed to download {}@{} from crates.io", name, version);
    }
    let bytes = resp.bytes().await?.to_vec();
    Ok((bytes, version))
}

/// Extract a `.crate` archive fully into `dest`. Returns the project root
/// (the single `name-version/` directory inside the tarball).
pub fn extract_crate(crate_bytes: &[u8], dest: &Path) -> Result<PathBuf> {
    std::fs::create_dir_all(dest)?;
    let decoder = flate2::read::GzDecoder::new(crate_bytes);
    let mut ar = tar::Archive::new(decoder);

    let mut root: Option<PathBuf> = None;
    for entry in ar.entries()? {
        let mut entry = entry?;
        let name = entry.path()?.to_string_lossy().into_owned();
        // All entries live under a single `name-version/` prefix.
        let rel = Path::new(&name);
        let top = rel
            .components()
            .next()
            .map(|c| c.as_os_str().to_string_lossy().into_owned());
        match (&root, top) {
            (None, Some(t)) => root = Some(PathBuf::from(t)),
            (Some(r), Some(t)) if r.to_string_lossy() != t => {
                anyhow::bail!("crate archive has multiple top-level dirs");
            }
            _ => {}
        }
        let out = dest.join(rel);
        if let Some(parent) = out.parent() {
            std::fs::create_dir_all(parent)?;
        }
        if entry.header().entry_type().is_dir() {
            std::fs::create_dir_all(&out)?;
        } else {
            let mut f = std::fs::File::create(&out)?;
            std::io::copy(&mut entry, &mut f)?;
        }
    }
    root.map(|r| dest.join(r))
        .context("crate archive is empty")
}

/// Publish one crate to crates.io using the documented wire format:
/// u32-LE json_len | json_metadata | u32-LE crate_len | crate_bytes.
pub async fn publish_to_crates_io(
    config: &Config,
    target_id: &str,
    project_root: &Path,
    token: &str,
) -> Result<()> {
    let archive = build_crate_archive(config, target_id, project_root)?;
    let crate_name = crate_name_for(config, target_id);
    let p = &config.project;

    let deps = serde_json::json!([]);
    let metadata = serde_json::json!({
        "name": crate_name,
        "vers": p.version,
        "deps": deps,
        "cksum": archive.sha256,
        "features": {},
        "authors": p.authors,
        "description": p.description.clone().unwrap_or_else(|| {
            "A stub Cargo.toml generated by Poly; see poly.ini for the real manifest.".to_string()
        }),
        "documentation": p.documentation,
        "homepage": p.homepage,
        "readme": p.readme,
        "readme_file": p.readme,
        "keywords": p.keywords,
        "categories": p.categories,
        "license": p.license,
        "license_file": p.license_file,
        "repository": p.repository,
        "links": serde_json::Value::Null,
        "rust_version": null,
    });
    let json = serde_json::to_vec(&metadata)?;

    let mut body = Vec::with_capacity(8 + json.len() + archive.bytes.len());
    body.extend_from_slice(&(json.len() as u32).to_le_bytes());
    body.extend_from_slice(&json);
    body.extend_from_slice(&(archive.bytes.len() as u32).to_le_bytes());
    body.extend_from_slice(&archive.bytes);

    let url = std::env::var("POLY_CRATES_IO_URL")
        .unwrap_or_else(|_| CRATES_IO_PUBLISH_URL.to_string());
    let resp = reqwest::Client::new()
        .put(&url)
        .header("Authorization", token)
        .header("Content-Type", "application/octet-stream")
        .header("Accept", "application/json")
        .header("User-Agent", concat!("poly/", env!("CARGO_PKG_VERSION")))
        .body(body)
        .send()
        .await
        .context("crates.io publish request failed")?;

    let status = resp.status();
    let text = resp.text().await.unwrap_or_default();

    if !status.is_success() {
        // crates.io returns {"errors":[{"detail": "..."}]}
        if let Ok(v) = serde_json::from_str::<serde_json::Value>(&text) {
            if let Some(errs) = v.get("errors").and_then(|e| e.as_array()) {
                let msgs: Vec<String> = errs
                    .iter()
                    .filter_map(|e| e.get("detail").and_then(|d| d.as_str()))
                    .map(|s| s.to_string())
                    .collect();
                if !msgs.is_empty() {
                    anyhow::bail!("crates.io rejected {}: {}", crate_name, msgs.join("; "));
                }
            }
        }
        anyhow::bail!("crates.io publish failed ({}): {}", status, text);
    }

    // Success response may carry warnings
    if let Ok(v) = serde_json::from_str::<serde_json::Value>(&text) {
        if let Some(w) = v.get("warnings") {
            tracing::warn!("crates.io warnings for {}: {}", crate_name, w);
        }
    }
    tracing::info!("Published {}@{} to crates.io", crate_name, p.version);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crate_archive_contains_poly_ini_and_stub() {
        let root = Path::new("/home/void01x/devin/poly");
        let config = poly_config::parse_poly_ini(&root.join("poly.ini").to_string_lossy())
            .expect("parse poly.ini");
        let archive = build_crate_archive(&config, "poly", root).expect("build crate");
        assert!(!archive.bytes.is_empty());
        assert_eq!(archive.sha256.len(), 64);

        // decompress and inspect
        let decoder = flate2::read::GzDecoder::new(archive.bytes.as_slice());
        let mut ar = tar::Archive::new(decoder);
        let mut entries: Vec<(String, Vec<u8>)> = Vec::new();
        for e in ar.entries().unwrap() {
            let mut e = e.unwrap();
            let name = e.path().unwrap().to_string_lossy().into_owned();
            let mut buf = Vec::new();
            std::io::Read::read_to_end(&mut e, &mut buf).unwrap();
            entries.push((name, buf));
        }
        let names: Vec<String> = entries.iter().map(|(n, _)| n.clone()).collect();
        assert!(names.iter().any(|n| n.ends_with("/poly.ini")));
        assert!(names.iter().any(|n| n.ends_with("/poly.lock")));
        assert!(names.iter().any(|n| n.ends_with("/Cargo.toml")));
        assert!(names.iter().any(|n| n.ends_with("/Cargo.toml.orig")));
        assert!(names.iter().any(|n| n.contains("crates_io.rs") || n.contains("main.rs")));
        // stub Cargo.toml must not declare real deps
        for (name, data) in &entries {
            if name.ends_with("/Cargo.toml") && !name.ends_with(".orig") {
                let s = String::from_utf8_lossy(data);
                assert!(s.contains("STUB GENERATED BY POLY"));
                assert!(!s.contains("[dependencies]"));
            }
        }
    }
}
